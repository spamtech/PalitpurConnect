import { Router } from "express";

import {
  register,
  verifyEmail,
  login,
  me,
  logout,
} from "../controllers/auth.controller.js";

import { authenticate } from "../middleware/auth.middleware.js";

const router = Router();

/*
|--------------------------------------------------------------------------
| Registration
|--------------------------------------------------------------------------
*/

router.post(
  "/register",
  register
);

/*
|--------------------------------------------------------------------------
| Email Verification
|--------------------------------------------------------------------------
*/

router.post(
  "/verify-email",
  verifyEmail
);

/*
|--------------------------------------------------------------------------
| Login
|--------------------------------------------------------------------------
*/

router.post(
  "/login",
  login
);

/*
|--------------------------------------------------------------------------
| Current User
|--------------------------------------------------------------------------
*/

router.get(
  "/me",
  authenticate,
  me
);

/*
|--------------------------------------------------------------------------
| Logout
|--------------------------------------------------------------------------
*/

router.post(
  "/logout",
  authenticate,
  logout
);

export default router;